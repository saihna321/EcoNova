const LanguageContext = createContext(null);

function getInitialLanguage() {
  if (typeof window === "undefined") return "en";
  try {
    const stored = window.localStorage.getItem("econova-language");
    return translations[stored] ? stored : "en";
  } catch {
    return "en";
  }
}

function interpolate(template, vars = {}) {
  return template.replace(/\{\{(\w+)\}\}/g, (_, key) => String(vars[key] ?? ""));
}

export function translate(language, key, vars) {
  const value = translations[language]?.[key] ?? translations.en[key] ?? key;
  return interpolate(value, vars);
}

export function LanguageProvider({ children }) {
  const [language, setLanguageState] = useState(getInitialLanguage);

  useEffect(() => {
    try {
      window.localStorage.setItem("econova-language", language);
    } catch {
      // Language still updates in memory if storage is unavailable.
    }
    document.documentElement.lang = language;
  }, [language]);

  const value = useMemo(
    () => ({
      language,
      dateLocale: dateLocales[language] ?? dateLocales.en,
      languages: languageOptions,
      setLanguage: (nextLanguage) => {
        if (translations[nextLanguage]) {
          setLanguageState(nextLanguage);
        }
      },
      t: (key, vars) => translate(language, key, vars),
    }),
    [language]
  );

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) {
    return {
      language: "en",
      dateLocale: dateLocales.en,
      languages: languageOptions,
      setLanguage: () => {},
      t: (key, vars) => translate("en", key, vars),
    };
  }
  return context;
}
